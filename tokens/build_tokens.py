STRINGS_HEADER = "Spoolwarden strings. GENERATED by build_tokens.py from strings/en.json. Do not edit by hand."
ICONS_DIR = HERE.parent / "icons"
WEB_SHARED_DIR = HERE.parent / "web-shared"
SHARED_STATIC_DIR = HERE.parent / "server" / "filament_kit" / "shared_static"
DRAWABLE_DIR = ANDROID_MAIN / "res" / "drawable"
SVG_NS = "http://www.w3.org/2000/svg"
ICON_ATTRS = ("fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin")
