#!/usr/bin/env python3
"""Generate tokens.css from tokens.json (standard library only).

Usage:
    python build_tokens.py           write tokens.css and theme-init.js next to tokens.json, and the three Android files
    python build_tokens.py --check   exit 1 when any of the five files differs from what tokens.json generates

Layout of the generated file (foundations sections 5 and 6.2):
  * Console on bare :root (light) and the two dark selectors.
  * Every other theme under :root[data-look="<name>"] with the same three selectors.
  * Preview tile blocks (08 section 3.4) follow the theme blocks: colour, type and radius only, under [data-look] without :root.
  * Phone overrides (max-width 600px) and prefers-reduced-motion blocks come last so they win ties.
"""
import argparse
import json
import math
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
JSON_PATH = HERE / "tokens.json"
CSS_PATH = HERE / "tokens.css"
JS_PATH = HERE / "theme-init.js"
ANDROID_MAIN = HERE.parent / "android" / "app" / "src" / "main"
KT_PACKAGE = "com.thompsonfabco.filamentkit.ui.theme"
KT_PATH = ANDROID_MAIN.joinpath("java", *KT_PACKAGE.split("."), "SpoolwardenTokens.kt")
WINDOW_PATH = ANDROID_MAIN / "res" / "values" / "sw_window.xml"
WINDOW_NIGHT_PATH = ANDROID_MAIN / "res" / "values-night" / "sw_window.xml"
HEADER = "Spoolwarden design tokens. GENERATED by build_tokens.py from tokens.json. Do not edit by hand."

COLOUR_ORDER = [
    "bg", "surface", "surface-2", "surface-3", "text", "muted", "border", "border-strong",
    "accent", "accent-hover", "on-accent", "accent-soft", "accent-text",
    "ok", "ok-soft", "warn", "warn-soft", "bad", "bad-soft", "on-bad", "info", "info-soft",
    "focus", "scrim", "code",
]
TYPE_ORDER = ["sans", "mono", "fs-xs", "fs-s", "fs-m", "fs-b", "fs-l", "fs-xl", "fs-2xl",
              "lh-body", "lh-title", "fw-text", "fw-label", "fw-title"]
SIZE_ORDER = ["ctl", "top", "rail", "tab", "row", "gap", "drawer", "hairline", "nav-mark", "thumb", "qr", "side-w", "list-w",
              "content-max", "label-col", "thumb-s", "swatch-row-w", "swatch-row-h", "swatch-head", "empty-mark", "chip",
              "slot-label", "port-field", "column-max", "preview-max", "list-pane"]
# Groups that hold values for one platform only: type.android and elevation.android (version 2) are Android's, not CSS.
PLATFORM_ONLY = ("android",)
MOTION_ORDER = ["t-fast", "t", "t-slow", "ease"]


def selectors(name):
    """Return (light, dark_media, dark_attr) selectors for a theme."""
    if name == "console":
        return ":root", ':root:not([data-theme="light"])', ':root[data-theme="dark"]'
    look = f'[data-look="{name}"]'
    return f":root{look}", f':root{look}:not([data-theme="light"])', f':root{look}[data-theme="dark"]'


def decl(name, value):
    return f"--{name}: {value};"


def ordered(d, order):
    keys = [k for k in order if k in d] + sorted(k for k in d if k not in order)
    return [(k, d[k]) for k in keys]


def non_phone(d):
    return {k: v for k, v in d.items() if not k.endswith("-phone")}


def web(d):
    return {k: v for k, v in d.items() if k not in PLATFORM_ONLY}


def light_decls(t):
    ex = t.get("extra", {})
    out = ["color-scheme: light;"]
    out += [decl(k, v) for k, v in ordered(t["light"], COLOUR_ORDER)]
    out += [decl(k, v) for k, v in ordered(ex.get("colour", {}).get("light", {}), [])]
    out += [decl(k, v) for k, v in ordered(web(t["type"]), TYPE_ORDER)]
    out += [decl(k, v) for k, v in ordered(ex.get("type", {}), [])]
    out += [decl(k, v) for k, v in t["space"].items()]
    out += [decl(k, v) for k, v in ex.get("space", {}).items()]
    out += [decl(k, v) for k, v in t["radius"].items()]
    out += [decl(k, v) for k, v in ex.get("radius", {}).items()]
    size = {("ctl" if k == "ctl" else k): v for k, v in non_phone(t["size"]).items()}
    out += [decl(k, v) for k, v in ordered(size, SIZE_ORDER)]
    out += [decl(k, v) for k, v in non_phone(ex.get("size", {})).items()]
    out += [decl(k, v) for k, v in t["elevation"]["light"].items()]
    out += [decl(k, v) for k, v in ex.get("elevation", {}).get("light", {}).items()]
    out += [decl(k, v) for k, v in ordered(t["motion"], MOTION_ORDER)]
    return out


def dark_decls(t):
    ex = t.get("extra", {})
    out = ["color-scheme: dark;"]
    out += [decl(k, v) for k, v in ordered(t["dark"], COLOUR_ORDER)]
    out += [decl(k, v) for k, v in ordered(ex.get("colour", {}).get("dark", {}), [])]
    out += [decl(k, v) for k, v in t["elevation"]["dark"].items()]
    out += [decl(k, v) for k, v in ex.get("elevation", {}).get("dark", {}).items()]
    return out


def phone_decls(t):
    """Size tokens that change at 600 px and below: 'ctl-phone' -> --ctl, 'X-phone' -> --X."""
    out = []
    for group in (t["size"], t.get("extra", {}).get("size", {})):
        for k, v in group.items():
            if k.endswith("-phone"):
                base = k[: -len("-phone")]
                if group.get(base) != v:
                    out.append(decl(base, v))
    return out


def block(selector, lines, indent=""):
    body = "\n".join(f"{indent}  {line}" for line in lines)
    return f"{indent}{selector} {{\n{body}\n{indent}}}"


def tile_light_decls(t):
    """Light colour, type and radius tokens of a theme (no size, elevation or motion) for its preview tile."""
    ex = t.get("extra", {})
    out = [decl(k, v) for k, v in ordered(t["light"], COLOUR_ORDER)]
    out += [decl(k, v) for k, v in ordered(ex.get("colour", {}).get("light", {}), [])]
    out += [decl(k, v) for k, v in ordered(web(t["type"]), TYPE_ORDER)]
    out += [decl(k, v) for k, v in ordered(ex.get("type", {}), [])]
    out += [decl(k, v) for k, v in t["radius"].items()]
    out += [decl(k, v) for k, v in ex.get("radius", {}).items()]
    return out


def tile_dark_decls(t):
    """Dark colour tokens of a theme for its preview tile."""
    ex = t.get("extra", {})
    out = [decl(k, v) for k, v in ordered(t["dark"], COLOUR_ORDER)]
    out += [decl(k, v) for k, v in ordered(ex.get("colour", {}).get("dark", {}), [])]
    return out


def generate(data):
    parts = [
        f"/* {HEADER} */",
        "",
    ]
    themes = data["themes"]
    for name, t in themes.items():
        light, dark_media, dark_attr = selectors(name)
        profile = ", ".join(f"{k}: {v}" for k, v in t["profile"].items())
        parts.append(f"/* {t['label']} ({profile}) */")
        parts.append(block(light, light_decls(t)))
        dd = dark_decls(t)
        parts.append("@media (prefers-color-scheme: dark) {\n" + block(dark_media, dd, "  ") + "\n}")
        parts.append(block(dark_attr, dd))
        parts.append("")
    parts.append("/* Preview tiles: a theme's colour, type and radius under any ancestor, for the theme picker */")
    for name, t in themes.items():
        look = f'[data-look="{name}"]'
        dd = tile_dark_decls(t)
        parts.append(block(look, tile_light_decls(t)))
        parts.append("@media (prefers-color-scheme: dark) {\n" + block(f':root:not([data-theme="light"]) {look}', dd, "  ") + "\n}")
        parts.append(block(f':root[data-theme="dark"] {look}', dd))
    parts.append("")
    parts.append("/* Phone: control height and chrome sizes at 600 px and below */")
    for name, t in themes.items():
        pd = phone_decls(t)
        if pd:
            parts.append("@media (max-width: 600px) {\n" + block(selectors(name)[0], pd, "  ") + "\n}")
    parts.append("")
    parts.append("/* Reduced motion: all durations 0 ms */")
    sel = ",\n".join(selectors(n)[0] for n in themes)
    parts.append(
        "@media (prefers-reduced-motion: reduce) {\n  "
        + sel.replace("\n", "\n  ")
        + " {\n    --t-fast: 0ms;\n    --t: 0ms;\n    --t-slow: 0ms;\n  }\n}"
    )
    return "\n".join(parts) + "\n"


def generate_js(data):
    keys = ", ".join(json.dumps(k) for k in data["themes"])
    return (
        f"// {HEADER}\n"
        "(function (r) {\n"
        "  var a = null, l = null;\n"
        '  try { a = localStorage.getItem("spoolwarden.appearance"); l = localStorage.getItem("spoolwarden.look"); } catch (e) {}\n'
        '  if (a === "light" || a === "dark") r.setAttribute("data-theme", a);\n'
        f'  if ([{keys}].indexOf(l) >= 0) r.setAttribute("data-look", l);\n'
        "})(document.documentElement);\n"
    )


def camel(name):
    """Token name in lower camel case: surface-2 -> surface2, nav-mark -> navMark, r-s -> rS."""
    head, *rest = name.split("-")
    return head + "".join(w[:1].upper() + w[1:] for w in rest)


def pascal(name):
    c = camel(name)
    return c[:1].upper() + c[1:]


def number(text):
    """A decimal number as Kotlin writes it without a suffix: 16.0 -> '16', 11.5 -> '11.5'."""
    v = float(text)
    return str(int(v)) if v == int(v) else repr(v)


def kt_float(text):
    return number(text) + "f"


def kt_length(text, unit):
    m = re.fullmatch(r"(-?[0-9.]+)" + unit, text.strip())
    if not m:
        raise ValueError(f"not a {unit} length: {text!r}")
    return m.group(1)


def kt_dp(text):
    return number(kt_length(text, "px")) + ".dp"


def kt_sp(text):
    return number(float(kt_length(text, "rem")) * 16) + ".sp"


def kt_ms(text):
    return str(int(float(kt_length(text, "ms"))))


def argb(text):
    """(alpha, r, g, b) of '#rrggbb', 'rgb(R G B / A)' or 'rgba(R,G,B,A)'; alpha rounded to the nearest of 256 steps."""
    t = text.strip()
    if re.fullmatch(r"#[0-9a-fA-F]{6}", t):
        return 255, int(t[1:3], 16), int(t[3:5], 16), int(t[5:7], 16)
    m = re.fullmatch(r"rgba?\(\s*([0-9]+)[\s,]+([0-9]+)[\s,]+([0-9]+)\s*[,/]\s*([0-9.]+)\s*\)", t)
    if not m:
        raise ValueError(f"not a colour: {text!r}")
    a = math.floor(float(m.group(4)) * 255 + 0.5)
    return a, int(m.group(1)), int(m.group(2)), int(m.group(3))


def kt_color(text):
    a, r, g, b = argb(text)
    return f"Color(0x{a:02X}{r:02X}{g:02X}{b:02X})"


def xml_color(text):
    a, r, g, b = argb(text)
    return f"#{r:02X}{g:02X}{b:02X}" if a == 255 else f"#{a:02X}{r:02X}{g:02X}{b:02X}"


def kt_family(name):
    return {"default": "Default", "monospace": "Monospace", "serif": "Serif", "sans-serif": "SansSerif"}[name]


def kt_easing(text):
    m = re.fullmatch(r"cubic-bezier\(([^)]*)\)", text.strip())
    if not m:
        raise ValueError(f"not a cubic-bezier: {text!r}")
    return "CubicBezierEasing(" + ", ".join(kt_float(x.strip()) for x in m.group(1).split(",")) + ")"


def kt_ring(shadow):
    """Ring.<Token> for a '0 0 0 1px var(--token)' part of an elevation value, null when there is none."""
    m = re.search(r"0 0 0 1px var\(--([a-z0-9-]+)\)", shadow)
    return f"Ring.{pascal(m.group(1))}" if m else "null"


def size_keys(size):
    """Size keys in generated order, each X-phone right after X."""
    keys = []
    for k, _ in ordered(non_phone(size), SIZE_ORDER):
        keys.append(k)
        if k + "-phone" in size:
            keys.append(k + "-phone")
    return keys + sorted(k for k in size if k.endswith("-phone") and k not in keys)


def kt_size_name(key):
    return "control" if key == "ctl" else "controlPhone" if key == "ctl-phone" else camel(key)


def kt_wrap(items, indent, per_line):
    pad = " " * indent
    return "\n".join(pad + ", ".join(items[i:i + per_line]) + "," for i in range(0, len(items), per_line))


def kt_colours(colours):
    items = [f"{camel(k)} = {kt_color(v)}" for k, v in ordered(colours, COLOUR_ORDER)]
    return "SpoolwardenColors(\n" + kt_wrap(items, 12, 3) + "\n        )"


def kt_theme(name, t):
    ty = t["type"]
    sizes = [f"{'xxl' if k == 'fs-2xl' else k[3:]} = {kt_sp(ty[k])}" for k in TYPE_ORDER if k.startswith("fs-")]
    weights = (f"lineBody = {kt_float(ty['lh-body'])}, lineTitle = {kt_float(ty['lh-title'])}, "
               f"weightText = {int(ty['fw-text'])}, weightLabel = {int(ty['fw-label'])}, weightTitle = {int(ty['fw-title'])},")
    el = t["elevation"]
    p = t["profile"]
    m = t["motion"]
    out = [
        f"    val {name} = ThemeTokens(",
        f"        light = {kt_colours(t['light'])},",
        f"        dark = {kt_colours(t['dark'])},",
        "        type = SwTypeTokens(",
        f"            sans = FontFamily.{kt_family(ty['android']['sans'])}, mono = FontFamily.{kt_family(ty['android']['mono'])},",
        kt_wrap(sizes, 12, 7),
        "            " + weights,
        "        ),",
        "        space = Spacing(" + ", ".join(f"{k} = {kt_dp(v)}" for k, v in t["space"].items()) + "),",
        "        sizes = SwSizes(",
        kt_wrap([f"{kt_size_name(k)} = {kt_dp(t['size'][k])}" for k in size_keys(t["size"])], 12, 4),
        "        ),",
        "        radius = SwRadius(" + ", ".join(f"{camel(k)} = {kt_dp(v)}" for k, v in t["radius"].items()) + "),",
    ]
    for mode in ("light", "dark"):
        out.append(f"        elevation{mode.capitalize()} = SwElevation("
                   f"e0 = SwShadow({kt_dp(el['android']['e0'])}, ring = {kt_ring(el[mode]['e0'])}), "
                   f"e2 = SwShadow({kt_dp(el['android']['e2'])}, ring = {kt_ring(el[mode]['e2'])})),")
    out.append(f"        motion = SwMotion(fast = {kt_ms(m['t-fast'])}, base = {kt_ms(m['t'])}, slow = {kt_ms(m['t-slow'])}, "
               f"easing = {kt_easing(m['ease'])}),")
    out.append(f"        profile = LayoutProfile(NavStyle.{pascal(p['nav'])}, CollectionStyle.{pascal(p['collection'])}, "
               f"DetailStyle.{pascal(p['detail'])}),")
    out.append("    )")
    return "\n".join(out)


def generate_kt(data):
    themes = data["themes"]
    parts = [
        f"// {HEADER}",
        f"package {KT_PACKAGE}",
        "",
        "import androidx.compose.animation.core.CubicBezierEasing",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.text.font.FontFamily",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.sp",
        "",
        "internal object SpoolwardenTokens {",
    ]
    for name, t in themes.items():
        parts.append(kt_theme(name, t))
    parts.append("")
    parts.append("    fun of(look: Look): ThemeTokens = when (look) {")
    parts.append("        " + "; ".join(f"Look.{pascal(n)} -> {n}" for n in themes))
    parts.append("    }")
    parts.append("}")
    return "\n".join(parts) + "\n"


def generate_window(data, night):
    c = data["themes"]["console"]
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {HEADER} -->\n"
        "<resources>\n"
        f'    <color name="sw_window_bg">{xml_color(c["dark" if night else "light"]["bg"])}</color>\n'
        f'    <color name="sw_launcher_bg">{xml_color(c["light"]["accent"])}</color>\n'
        f'    <color name="sw_launcher_bg_nightly">{xml_color(c["light"]["warn"])}</color>\n'
        "</resources>\n"
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit non-zero when a generated file is out of date")
    args = ap.parse_args()
    with open(JSON_PATH, encoding="utf-8") as f:
        data = json.load(f)
    outputs = [
        (CSS_PATH, generate(data), CSS_PATH.name),
        (JS_PATH, generate_js(data), JS_PATH.name),
        (KT_PATH, generate_kt(data), KT_PATH.name),
        (WINDOW_PATH, generate_window(data, False), "values/" + WINDOW_PATH.name),
        (WINDOW_NIGHT_PATH, generate_window(data, True), "values-night/" + WINDOW_NIGHT_PATH.name),
    ]
    if args.check:
        failed = False
        for path, text, label in outputs:
            try:
                with open(path, encoding="utf-8", newline="") as f:
                    current = f.read()
            except FileNotFoundError:
                print(f"FAIL: {path} does not exist", file=sys.stderr)
                failed = True
                continue
            if current != text:
                print(f"FAIL: {label} differs from what {JSON_PATH.name} generates; run build_tokens.py", file=sys.stderr)
                failed = True
            else:
                print(f"OK: {label} matches {JSON_PATH.name}")
        return 1 if failed else 0
    for path, text, _ in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {path} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
