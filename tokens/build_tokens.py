#!/usr/bin/env python3
"""Generate tokens.css from tokens.json (standard library only).

Usage:
    python build_tokens.py           write tokens.css and theme-init.js next to tokens.json, the three Android files, and
                                     strings/strings.js and res/values/strings.xml from strings/en.json
                                     also copies tokens.css, theme-init.js, strings.js, icons/sprite.svg and every file of
                                     web-shared/ into server/filament_kit/shared_static/ (the Hub serves them from there)
    python build_tokens.py --check   exit 1 when any generated file (the seven above, icons/sprite.svg, the icon drawables
                                     and the shared_static copies) differs from what its source generates, or an icon
                                     drawable or shared_static file has no source

Layout of the generated file (foundations sections 5 and 6.2):
  * Console on bare :root (light) and the two dark selectors.
  * Every other theme under :root[data-look="<name>"] with the same three selectors.
  * Preview tile blocks (08 section 3.4) follow the theme blocks: colour, type and radius only, under [data-look] without :root.
  * Phone overrides (max-width 600px) and prefers-reduced-motion blocks come last so they win ties.
"""
