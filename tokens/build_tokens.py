PLACEHOLDER = re.compile(r"\{([a-z][a-z0-9_]*)\}")
RESERVED = {"product": "app_name", "command": "command_name"}
STRING_KEY = re.compile(r"[a-z][a-z0-9_]*")


def load_strings(path):
    """Catalogue as {key: text or {"one": text, "other": text}} with {product} and {command} filled in."""
    with open(path, encoding="utf-8") as f:
        raw = json.load(f)
    for key, entry in RESERVED.items():
        if not isinstance(raw.get(entry), str) or PLACEHOLDER.search(raw[entry]):
            raise ValueError(f"{entry} must be a text without placeholders")

    def fill(text):
        return PLACEHOLDER.sub(lambda m: raw[RESERVED[m.group(1)]] if m.group(1) in RESERVED else m.group(0), text)

    out = {}
    for key, value in raw.items():
        if not STRING_KEY.fullmatch(key):
            raise ValueError(f"string key {key!r} is not lower snake case")
        if isinstance(value, dict):
            if set(value) != {"one", "other"} or not all(isinstance(v, str) for v in value.values()):
                raise ValueError(f"{key}: a plural needs the texts 'one' and 'other'")
            out[key] = {q: fill(t) for q, t in value.items()}
        elif isinstance(value, str):
            out[key] = fill(value)
        else:
            raise ValueError(f"{key}: a text or an object of plural forms")
    return out


def string_forms(value):
    return list(value.values()) if isinstance(value, dict) else [value]


def placeholder_order(value):
    """Placeholder names of an entry in order of first appearance (over the plural forms in order)."""
    names = []
    for text in string_forms(value):
        for n in PLACEHOLDER.findall(text):
            if n not in names:
                names.append(n)
    return names


def generate_strings_js(strings):
    lines = [f"// {STRINGS_HEADER}", "window.SW_TEXT = Object.freeze({"]
    for key, value in strings.items():
        if isinstance(value, dict):
            text = "{ " + ", ".join(f'"{q}": {json.dumps(value[q], ensure_ascii=False)}' for q in ("one", "other")) + " }"
        else:
            text = json.dumps(value, ensure_ascii=False)
        lines.append(f"  {json.dumps(key)}: {text},")
    lines.append("});")
    return "\n".join(lines) + "\n"


def xml_text(text, order):
    """Android resource text: placeholders numbered by first appearance ({count} -> %n$d, others %n$s), then escaped.

    A literal % is %% only in a string with placeholders (Android turns %% back into % only when it formats the string
    with arguments). A text with leading or trailing whitespace or a run of spaces is written in double quotes, because
    Android trims and collapses whitespace in an unquoted string."""
    fmt = bool(order)
    parts = []
    pos = 0
    for m in PLACEHOLDER.finditer(text):
        parts.append(xml_escape(text[pos:m.start()], fmt))
        i = order.index(m.group(1)) + 1
        parts.append(f"%{i}${'d' if m.group(1) == 'count' else 's'}")
        pos = m.end()
    parts.append(xml_escape(text[pos:], fmt))
    out = xml_lead("".join(parts))
    if text != text.strip() or "  " in text:
        out = f'"{out}"'
    return out


def xml_escape(text, fmt=True):
    for old, rep in (("\\", "\\\\"), ("'", "\\'"), ('"', '\\"'), ("&", "&amp;"), ("<", "&lt;"), ("\n", "\\n")):
        text = text.replace(old, rep)
    return text.replace("%", "%%") if fmt else text


def xml_lead(text):
    """A leading @ or ? is escaped with a backslash."""
    return "\\" + text if text[:1] in "@?" else text


def generate_strings_xml(strings):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {STRINGS_HEADER} -->", "<resources>"]
    for key, value in strings.items():
        order = placeholder_order(value)
        if order:
            lines.append("    <!-- " + " ".join(f"{i}={n}" for i, n in enumerate(order, 1)) + " -->")
        if isinstance(value, dict):
            lines.append(f'    <plurals name="{key}">')
            for q in ("one", "other"):
                lines.append(f'        <item quantity="{q}">{xml_text(value[q], order)}</item>')
            lines.append("    </plurals>")
        else:
            attr = ' formatted="false"' if not order and "%" in value else ""
            lines.append(f'    <string name="{key}"{attr}>{xml_text(value, order)}</string>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def load_icons(folder):
    """Read icons/<folder>/*.svg: {name: (root attributes, [path attributes with d])}. Anything but <path> is an error."""
    out = {}
    for path in sorted((ICONS_DIR / folder).glob("*.svg")):
        label = f"icons/{folder}/{path.name}"
        root = ET.parse(path).getroot()
        if root.tag != f"{{{SVG_NS}}}svg":
            raise SystemExit(f"{label}: the root element is not <svg>")
        if root.get("viewBox") != "0 0 24 24":
            raise SystemExit(f'{label}: viewBox is not "0 0 24 24"')
        paths = []
        for el in root:
            if el.tag != f"{{{SVG_NS}}}path":
                raise SystemExit(f"{label}: only <path> elements are allowed, found <{el.tag.rpartition('}')[2]}>")
            if not el.get("d"):
                raise SystemExit(f"{label}: a <path> has no d")
            paths.append(dict(el.attrib))
        out[path.stem] = ({k: root.get(k) for k in ICON_ATTRS if root.get(k) is not None}, paths)
    return out


def generate_sprite(icons, shapes):
    lines = ["<!-- Spoolwarden icon sprite. GENERATED by build_tokens.py from icons/src and icons/status. Do not edit by hand. -->",
             f'<svg xmlns="{SVG_NS}" class="sprite" aria-hidden="true" width="0" height="0">']
    for prefix, group in (("i", icons), ("s", shapes)):
        for name, (attrs, paths) in group.items():
            extra = "".join(f' {k}="{attrs[k]}"' for k in ICON_ATTRS if k in attrs)
            lines.append(f'  <symbol id="{prefix}-{name}" viewBox="0 0 24 24"{extra}>')
            for p in paths:
                own = "".join(f' {k}="{p[k]}"' for k in ICON_ATTRS if k in p)
                lines.append(f'    <path{own} d="{p["d"]}"/>')
            lines.append("  </symbol>")
    lines.append("</svg>")
    return "\n".join(lines) + "\n"


def generate_drawable(source, attrs, paths):
    """08 section 11: one <path> per source path; pathData copied from d; the colour that is not used is #00000000."""
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             f"<!-- Spoolwarden icon. GENERATED by build_tokens.py from {source}. Do not edit by hand. -->",
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    android:width="24dp"', '    android:height="24dp"', '    android:viewportWidth="24"',
             '    android:viewportHeight="24">']
    for p in paths:
        a = {**attrs, **{k: v for k, v in p.items() if k in ICON_ATTRS}}
        filled = a.get("fill", "black") != "none"
        stroked = a.get("stroke") is not None
        lines.append("    <path")
        lines.append(f'        android:pathData="{p["d"]}"')
        lines.append(f'        android:fillColor="{"#FF000000" if filled else "#00000000"}"')
        lines.append(f'        android:strokeColor="{"#FF000000" if stroked else "#00000000"}"' + ("" if stroked else " />"))
        if stroked:
            lines.append(f'        android:strokeWidth="{a.get("stroke-width", "1")}"')
            lines.append(f'        android:strokeLineCap="{a.get("stroke-linecap", "butt")}"')
            lines.append(f'        android:strokeLineJoin="{a.get("stroke-linejoin", "miter")}" />')
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def icon_outputs():
    """(path, text, label, source) for the sprite and every drawable."""
    icons, shapes = load_icons("src"), load_icons("status")
    out = [(ICONS_DIR / "sprite.svg", generate_sprite(icons, shapes), "icons/sprite.svg", "icons/src and icons/status")]
    for folder, prefix, group in (("src", "sw_ic_", icons), ("status", "sw_st_", shapes)):
        for name, (attrs, paths) in group.items():
            file = prefix + name.replace("-", "_") + ".xml"
            source = f"icons/{folder}/{name}.svg"
            out.append((DRAWABLE_DIR / file, generate_drawable(source, attrs, paths), "drawable/" + file, source))
    return out


def shared_outputs(outputs):
    """(path, text, label, source) for the byte-identical copies the Hub serves (08 section 1): the generated tokens.css,
    theme-init.js, strings.js and sprite.svg, and every regular file of web-shared/ when that folder exists."""
    by_path = {path: text for path, text, *_ in outputs}
    out = []
    for src in (CSS_PATH, JS_PATH, STRINGS_JS_PATH, ICONS_DIR / "sprite.svg"):
        out.append((SHARED_STATIC_DIR / src.name, by_path[src], "shared_static/" + src.name, src.parent.name + "/" + src.name))
    if WEB_SHARED_DIR.is_dir():
        for src in sorted(WEB_SHARED_DIR.iterdir()):
            if src.is_file():
                with open(src, encoding="utf-8", newline="") as f:
                    out.append((SHARED_STATIC_DIR / src.name, f.read(), "shared_static/" + src.name, "web-shared/" + src.name))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit non-zero when a generated file is out of date")
    args = ap.parse_args()
    with open(JSON_PATH, encoding="utf-8") as f:
        data = json.load(f)
    strings = load_strings(STRINGS_SRC)
    outputs = [
        (CSS_PATH, generate(data), CSS_PATH.name),
        (JS_PATH, generate_js(data), JS_PATH.name),
        (KT_PATH, generate_kt(data), KT_PATH.name),
        (WINDOW_PATH, generate_window(data, False), "values/" + WINDOW_PATH.name),
        (WINDOW_NIGHT_PATH, generate_window(data, True), "values-night/" + WINDOW_NIGHT_PATH.name),
        (STRINGS_JS_PATH, generate_strings_js(strings), "strings.js"),
        (STRINGS_XML_PATH, generate_strings_xml(strings), "values/strings.xml"),
    ]
    sources = {path: STRINGS_SRC.parent.name + "/" + STRINGS_SRC.name for path in (STRINGS_JS_PATH, STRINGS_XML_PATH)}
    for path, text, label, source in icon_outputs():
        outputs.append((path, text, label))
        sources[path] = source
    for path, text, label, source in shared_outputs(outputs):
        outputs.append((path, text, label))
        sources[path] = source
    if args.check:
        failed = False
        known = {path for path, _, _ in outputs}
        if SHARED_STATIC_DIR.is_dir():
            for stray in sorted(SHARED_STATIC_DIR.iterdir()):
                if stray not in known:
                    print(f"FAIL: shared_static/{stray.name} has no source", file=sys.stderr)
                    failed = True
        for stray in sorted(DRAWABLE_DIR.glob("sw_ic_*.xml")) + sorted(DRAWABLE_DIR.glob("sw_st_*.xml")):
            if stray not in known:
                print(f"FAIL: drawable/{stray.name} has no source in icons/", file=sys.stderr)
                failed = True
        for path, text, label in outputs:
            source = sources.get(path, JSON_PATH.name)
            try:
                with open(path, encoding="utf-8", newline="") as f:
                    current = f.read()
            except FileNotFoundError:
                print(f"FAIL: {path} does not exist", file=sys.stderr)
                failed = True
                continue
            if current != text:
                print(f"FAIL: {label} differs from what {source} generates; run build_tokens.py", file=sys.stderr)
                failed = True
            else:
                print(f"OK: {label} matches {source}")
        return 1 if failed else 0
    for path, text, _ in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {path} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
